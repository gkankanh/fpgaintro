#!/usr/bin/env python3
"""
mktasks.py — regenerate .vscode/tasks.json so every lesson appears by name.

Why this exists
---------------
Selecting a lesson in an editor should be a mouse click on its name. VS Code
cannot do that from the Explorer — tasks only see the focused editor tab, not
what is highlighted in the file tree — so instead this writes one task PER
LESSON. The Run Task list then reads like a menu of lessons, and picking one
is a click.

Run after adding a lesson:    make tasks
"""
from __future__ import annotations

import glob
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

HEADER = """// GENERATED by tools/mktasks.py — run `make tasks` after adding a lesson.
//
// One task per lesson, so Terminal > Run Task reads as a menu of lessons and
// choosing one is a mouse click. VS Code tasks cannot see what is selected in
// the Explorer — only the focused editor tab — which is why the lessons are
// enumerated here instead.
//
// Problem matchers are written INLINE. tasks.json has no way to declare named
// reusable matchers; names like $gcc come from extensions, not from this file.
"""

SIM_MATCHER = {
    "owner": "verilog",
    "fileLocation": ["relative", "${workspaceFolder}"],
    "pattern": {
        "regexp": r"^(.+?):(\d+):\s*(error|warning|sorry):\s*(.*)$",
        "file": 1, "line": 2, "severity": 3, "message": 4,
    },
}
LINT_MATCHER = {
    "owner": "verilog",
    "fileLocation": ["relative", "${workspaceFolder}"],
    "pattern": {
        "regexp": r"^%(Error|Warning)[^:]*:\s*(.+?):(\d+):(\d+):\s*(.*)$",
        "severity": 1, "file": 2, "line": 3, "column": 4, "message": 5,
    },
}


def lessons() -> list[tuple[str, str, bool, bool]]:
    """(dirname, pretty title, has_code, can_deploy) per NN-name directory.

    `can_deploy` requires the lesson's Makefile to define a TOP module, which
    is what the shared rules turn into a bitstream. Lesson 14 has plenty of
    Verilog but proves lessons 10 and 11 rather than building anything, so it
    gets a `sim` task and no `deploy` task -- offering to program a board with
    a formal proof would be a lie the task list told.
    """
    out = []
    for d in sorted(glob.glob(os.path.join(ROOT, "[0-9][0-9]-*"))):
        name = os.path.basename(d)
        num, slug = name.split("-", 1)
        built = bool(glob.glob(os.path.join(d, "*.v")))
        mk = os.path.join(d, "Makefile")
        deploy = built and os.path.isfile(mk) and \
            any(re.match(r"\s*TOP\s*=", ln) for ln in open(mk))
        out.append((name, f"{num} {slug.replace('-', ' ')}", built, deploy))
    return out


def task(label, cmd, cwd, matcher=None, default_build=False, group=None):
    t = {
        "label": label,
        "type": "shell",
        "command": cmd,
        "options": {"cwd": cwd},
        "presentation": {
            "reveal": "always", "panel": "dedicated", "clear": True,
        },
        "problemMatcher": matcher if matcher else [],
    }
    if default_build:
        t["group"] = {"kind": "build", "isDefault": True}
    elif group:
        t["group"] = group
    return t


def main() -> int:
    tasks = []
    ws = "${workspaceFolder}"

    # --- one DEPLOY and one SIM per built lesson -------------------------
    # Deploy first: it is the thing people hunt for, and VS Code preserves
    # this order in the Run Task list.
    for name, title, built, deploy in lessons():
        if not deploy:
            continue
        tasks.append(task(
            f"▶ deploy  {title}",
            "make bit && make prog",
            f"{ws}/{name}",
        ))

    for name, title, built, deploy in lessons():
        if not built:
            continue
        tasks.append(task(
            f"✓ sim     {title}",
            "make sim",
            f"{ws}/{name}",
            SIM_MATCHER,
        ))

    # --- the open-file variants, for when a lesson source is focused -----
    tasks.append(task("sim (file's lesson)", "make sim", "${fileDirname}",
                      SIM_MATCHER, default_build=True))
    tasks.append(task("lint (file's lesson)", "make lint", "${fileDirname}",
                      LINT_MATCHER))
    tasks.append(task("wave (file's lesson)", "make wave", "${fileDirname}"))
    tasks.append(task("synth — resource report (file's lesson)",
                      "make synth", "${fileDirname}"))
    tasks.append(task("graph — schematic SVG (file's lesson)",
                      "make graph", "${fileDirname}"))
    tasks.append(task("clean (file's lesson)", "make clean", "${fileDirname}"))

    # --- course-wide ------------------------------------------------------
    tasks.append(task("detect — is the board there?",
                      "toolchain/oss-cad-suite/bin/openFPGALoader --detect -b ulx3s",
                      ws))
    tasks.append(task("sim ALL lessons (regression)", "make sim-all", ws,
                      SIM_MATCHER, group="test"))
    tasks.append(task("lint ALL lessons", "make lint-all", ws, LINT_MATCHER))
    tasks.append(task("docs — serve the book locally", "make docs-serve", ws))

    out = os.path.join(ROOT, ".vscode", "tasks.json")
    body = json.dumps({"version": "2.0.0", "tasks": tasks},
                      indent=2, ensure_ascii=False)
    with open(out, "w") as f:
        f.write(HEADER + body + "\n")

    built = [t for t in tasks if t["label"].startswith("▶")]
    print(f"  {os.path.relpath(out, ROOT)}: {len(tasks)} tasks, "
          f"{len(built)} deployable lessons")
    for t in built:
        print(f"      {t['label']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
